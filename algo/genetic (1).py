    for p in pop_sizes:
        for m in mutation_rates:
            for g_p in gene_probs:
                for e in elite_sizes:
                    all_combinations.append({
                        'pop_size': p,
                        'mutation_rate': m,
                        'gene_mutation_prob': g_p,
                        'elite_size': e
                    })

    results = []
    total_configs = len(all_combinations)
    print(f"🔬 Lancement du tuning étendu : {total_configs} configurations ({n_runs_per_config} runs/config = {total_configs * n_runs_per_config} runs au total)...\n")

    for idx, config in enumerate(all_combinations, 1):
        total_gens = 0
        total_time = 0
        successes = 0

        for _ in range(n_runs_per_config):
            start = time.time()

            # Appel de l'algorithme génétique avec les paramètres de la grille
            best_sched, g = run_genetic_algorithm(
                pop_size=config['pop_size'],
                generations=1000,
                elite_size=config['elite_size']
            )
            exec_t = time.time() - start

            if cost(best_sched) == 0:
                successes += 1

            total_gens += g
            total_time += exec_t

        avg_gen = total_gens / n_runs_per_config
        avg_time = total_time / n_runs_per_config
        success_rate = (successes / n_runs_per_config) * 100

        results.append({
            'config': config,
            'avg_gen': avg_gen,
            'avg_time': avg_time,
            'success_rate': success_rate
        })

        print(f"[{idx}/{total_configs}] Config: Pop={config['pop_size']}, Mut={config['mutation_rate']}, GeneMut={config['gene_mutation_prob']}, Élite={config['elite_size']} "
              f"-> Temps: {avg_time:.2f}s | Générations: {avg_gen:.1f} | Succès: {success_rate:.0f}%")

    # 2. Meilleur résultat : Priorité au taux de succès (100%), puis au temps de calcul le plus rapide
    best_result = min(results, key=lambda x: (100 - x['success_rate'], x['avg_time'], x['avg_gen']))

    print("\n" + "="*50)
    print("🏆 MEILLEURE CONFIGURATION DÉCOUVRTE :")
    print("="*50)
    for k, v in best_result['config'].items():
        print(f" • {k}: {v}")
    print(f" • Temps moyen de résolution  : {best_result['avg_time']:.4f} s")
    print(f" • Générations moyennes       : {best_result['avg_gen']:.2f}")
    print(f" • Taux de succès (0 conflit) : {best_result['success_rate']:.1f}%")
    print("="*50)

    return best_result

