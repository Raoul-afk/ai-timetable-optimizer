import random

ROOMS = ["R101", "R102", "R103", "R104", "R105", "R106"]
SLOTS = [f"{d}_{h}" for d in ["MON", "TUE", "WED", "THU", "FRI"] for h in ["07:00", "09:30", "12:00", "14:30"]]
YEARS = ["A1", "A2", "A3", "A4", "A5"]
SUBJECTS_LOAD = {"MATH": 2, "PHYS": 2, "PROG": 1, "ANGL": 1, "HIST": 1, "ELEC": 1}

# Génération des sessions de cours
COURSES = []
for year in YEARS:
    for subj, count in SUBJECTS_LOAD.items():
        for sess in range(1, count + 1):
            COURSES.append(f"{subj}_{year}_{sess}")

def cost(sched):
    """Calcule le nombre de conflits (salle partagée ou même année au même moment)."""
    rooms, years, conflicts = {}, {}, 0
    for c, r, s in sched:
        y = c.split("_")[1]
        rooms.setdefault(s, {}).setdefault(r, 0)
        years.setdefault(s, {}).setdefault(y, 0)
        rooms[s][r] += 1
        years[s][y] += 1
    for s in rooms:
        conflicts += sum(v - 1 for v in rooms[s].values() if v > 1)
        conflicts += sum(v - 1 for v in years[s].values() if v > 1)
    return conflicts

def fitness(sched):
    """Fonction de fitness : plus il y a de conflits, plus la fitness est basse."""
    c = cost(sched)
    return 1.0 / (1.0 + c)

def run_genetic_algorithm(pop_size=100, generations=1000, elite_size=2,mutation_rates = 0.1, gene_probs = 0.1 ):
    # (a) Initial Population : Création de la population initiale de départ
    population = [[(c, random.choice(ROOMS), random.choice(SLOTS)) for c in COURSES] for _ in range(pop_size)]

    for g in range(generations):
        # (b) Fitness Function : Évaluation de chaque individu
        fits = [fitness(ind) for ind in population]

        # Vérification si une solution parfaite (0 conflit -> fitness = 1.0) est trouvée
        if max(fits) == 1.0:
            best_idx = fits.index(max(fits))
            print(f"✨ Solution parfaite trouvée à la génération {g} !")
            return population[best_idx], g

        # --- IMPLÉMENTATION DE L'ÉLITISME ---
        # 1. Associer chaque individu à sa fitness et trier du meilleur au pire (fitness décroissante)
        paired = list(zip(population, fits))
        paired.sort(key=lambda x: x[1], reverse=True)

        # 2. Extraire les meilleurs individus (l'élite)
        elites = [ind for ind, f in paired[:elite_size]]

        # Calcul des probabilités proportionnelles à la fitness (pour la roulette)
        total_fit = sum(fits)
        probabilities = [f / total_fit for f in fits]

        # 3. La nouvelle population commence directement avec l'élite
        new_population = list(elites)

        while len(new_population) < pop_size:
            # (c) Selection : Sélection probabiliste de 2 parents basée sur les pourcentages de fitness
            parent1, parent2 = random.choices(population, weights=probabilities, k=2)

            # (d) Cross-Over : Croisement en un point
            pt = random.randint(1, len(COURSES) - 1)
            child1 = parent1[:pt] + parent2[pt:]
            child2 = parent2[:pt] + parent1[pt:]

            # (e) Mutation : Application d'une modification aléatoire
            if random.random() < 0.1:
                child1 = [(c, random.choice(ROOMS), random.choice(SLOTS)) if random.random() < 0.1 else (c, r, s) for c, r, s in child1]
            if random.random() < 0.1:
                child2 = [(c, random.choice(ROOMS), random.choice(SLOTS)) if random.random() < 0.1 else (c, r, s) for c, r, s in child2]

            new_population.append(child1)
            if len(new_population) < pop_size:
                new_population.append(child2)

        population = new_population

    # Retourner le meilleur individu de la dernière génération si pas de 0 conflit parfait
    fits = [fitness(ind) for ind in population]
    best_idx = fits.index(max(fits))
    return population[best_idx], generations

